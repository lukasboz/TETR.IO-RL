"""Export the placement model for dependency-free browser/native inference."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from torch import nn

from .agent import DQNAgent
from .features import FEATURE_NAMES


def export_model(checkpoint: str | Path, output: str | Path, format: str = "json") -> dict:
    if format not in ("json", "rust"):
        raise ValueError("Export format must be json or rust")
    checkpoint, output = Path(checkpoint), Path(output)
    agent = DQNAgent.load(checkpoint)
    layers = []
    for layer in agent.online.layers:
        if isinstance(layer, nn.Linear):
            layers.append({"type": "linear", "weight": layer.weight.detach().cpu().tolist(),
                           "bias": layer.bias.detach().cpu().tolist()})
        elif isinstance(layer, nn.ReLU):
            layers.append({"type": "relu"})
        else:
            raise ValueError(f"Unsupported export layer: {type(layer).__name__}")
    payload = {"format": "tetrio-rl-dqn-v1", "feature_names": list(FEATURE_NAMES),
               "training_steps": agent.steps, "gradient_updates": agent.updates,
               "checkpoint_sha256": hashlib.sha256(checkpoint.read_bytes()).hexdigest(),
               "layers": layers}
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = output.with_name(output.name + ".tmp")
    # Validate every serialized parameter before producing executable source.
    serialized = json.dumps(payload, separators=(",", ":"), allow_nan=False)
    temporary.write_text(serialized if format == "json" else _rust_source(payload), encoding="utf-8")
    temporary.replace(output)
    return payload


def run(args) -> None:
    payload = export_model(args.checkpoint, args.output, args.format)
    print(f"Exported {payload['training_steps']:,}-placement model to {Path(args.output).resolve()}")


def _rust_source(payload: dict) -> str:
    parts = ["// Generated by tetrio_rl export. No external crate dependencies.",
             f"pub const TRAINING_STEPS: usize = {payload['training_steps']};",
             f"pub const FEATURE_DIM: usize = {len(FEATURE_NAMES)};",
             f"pub const CHECKPOINT_SHA256: &str = {json.dumps(payload['checkpoint_sha256'])};"]
    body = ["pub fn score(features: &[f32; FEATURE_DIM]) -> f32 {", "    let values = *features;"]
    for index, layer in enumerate(payload["layers"]):
        if layer["type"] == "relu":
            body.append("    let values = values.map(|v| v.max(0.0));")
            continue
        weight, bias = layer["weight"], layer["bias"]
        width, height = len(weight[0]), len(weight)
        rows = ["[" + ",".join(f"{v:.9e}f32" for v in row) + "]" for row in weight]
        parts.append(f"static WEIGHT_{index}: [[f32; {width}]; {height}] = [\n" + ",\n".join(rows) + "]; ")
        parts.append(f"static BIAS_{index}: [f32; {height}] = [" + ",".join(f"{v:.9e}f32" for v in bias) + "]; ")
        body.extend([f"    let mut output = [0.0f32; {height}];",
                     f"    for (i, row) in WEIGHT_{index}.iter().enumerate() {{",
                     f"        let mut sum = BIAS_{index}[i] as f64;",
                     "        for (weight, value) in row.iter().zip(values.iter()) {",
                     "            sum += (*weight as f64) * (*value as f64);",
                     "        }", "        output[i] = sum as f32;", "    }",
                     "    let values = output;"])
    body.extend(["    values[0]", "}"])
    return "\n".join(parts + body) + "\n"
